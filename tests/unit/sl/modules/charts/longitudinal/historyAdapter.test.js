import { describe, it, expect } from 'vitest';

import {
    buildKsHistory,
    buildSurveyHistory,
    buildYearAxis,
    detectHistorySurveyScales,
} from '@tba3/modules/sl/modules/charts/longitudinal/historyAdapter.js';

/**
 * The SL Entwicklung view used to *invent* its earlier years in the browser
 * (`measureHistory.js`). It now reads them out of `history.json`, which the API
 * answers `?comparison=year` with.
 *
 * Everything pinned here is a property of that read path that a chart cannot show is
 * broken: a generated year misread as measured, a timeline drawn in the wrong order or
 * a cohort silently mixed all render as clean, confident charts that say something
 * false. The demo fixture is regenerated by `tools/gen-sl-history-fixture.mjs`, so
 * these must hold for whatever it produces, not for one frozen file.
 */

const LEVELS = ['k.h.N.', 'KS 1', 'KS 2', 'KS 3', 'KS 4', 'KS 5'];

function schoolRow(
    counts,
    { year = '2026', simulated = false, fach = 'Deutsch', domaene = 'le' } = {},
) {
    const total = counts.reduce((sum, count) => sum + count, 0);
    return {
        id: 'school-1',
        type: 'school',
        name: 'Beispielschule',
        subject: { name: fach },
        domain: { id: domaene },
        properties: [
            { key: 'testPeriod', value: year },
            ...(simulated ? [{ key: 'simulated', value: 'true' }] : []),
        ],
        competenceLevels: LEVELS.map((nameShort, index) => ({
            nameShort,
            descriptiveStatistics: {
                total,
                frequency: counts[index] ?? 0,
                mean: total ? (counts[index] ?? 0) / total : 0,
            },
        })),
    };
}

function studentRow(
    id,
    { year = '2026', simulated = false, fach = 'Deutsch', tq = '3.0', sp = '4.0' } = {},
) {
    return {
        id,
        type: 'student',
        name: id,
        subject: { name: fach },
        properties: [
            ...(tq === null ? [] : [{ key: 'tq_mean', value: tq }]),
            ...(sp === null ? [] : [{ key: 'sp_mean', value: sp }]),
            { key: 'testPeriod', value: year },
            ...(simulated ? [{ key: 'simulated', value: 'true' }] : []),
        ],
        competenceLevels: [],
    };
}

describe('buildYearAxis', () => {
    it('sorts numerically and de-duplicates, whatever order the payload used', () => {
        // WHY: the box plot feeds this straight into `d3.scalePoint().domain()`, which
        // preserves array order. The server emits the measured block before the generated
        // one, so payload order puts the newest year first — drawn as-is that reads as a
        // four-year decline. Every year also appears on many rows (one per Fach/Domäne
        // plus every student), so a duplicate would collapse the axis onto itself.
        const history = [
            schoolRow([1, 1, 1, 1, 1, 1], { year: '2026' }),
            studentRow('a', { year: '2026' }),
            schoolRow([1, 1, 1, 1, 1, 1], { year: '2024', simulated: true }),
            schoolRow([1, 1, 1, 1, 1, 1], { year: '2025', simulated: true }),
            schoolRow([1, 1, 1, 1, 1, 1], { year: '2024', simulated: true, fach: 'Englisch' }),
        ];

        expect(buildYearAxis(history)).toEqual(['2024', '2025', '2026']);
    });

    it('is empty for a missing document rather than throwing', () => {
        // WHY: acquisition fails loud, but a dataset whose history.json is empty must
        // still render the host's empty state instead of taking the view down.
        expect(buildYearAxis(undefined)).toEqual([]);
        expect(buildYearAxis([])).toEqual([]);
    });
});

describe('buildKsHistory', () => {
    it('reports shares from frequency and total, not from the payload mean', () => {
        // WHY: `mean` is rounded to 4 dp at the source (0.0253 for 2/79). The chart stacks
        // these shares to 100 %, and rounded ones do not add up — the top band would be
        // visibly short of the axis.
        const timeline = buildKsHistory([schoolRow([2, 3, 12, 27, 21, 14])], 'Deutsch', 'le');

        expect(timeline).toHaveLength(1);
        const shares = Object.values(timeline[0].categories);
        expect(shares.reduce((sum, share) => sum + share, 0)).toBeCloseTo(100, 10);
        expect(timeline[0].categories['KS 3']).toBeCloseTo((27 / 79) * 100, 10);
    });

    it('keeps the payload band order, which Object.keys would re-sort', () => {
        // WHY: the legend and the stacking order follow these keys. `k.h.N.` is the lowest
        // rung and sorts after `KS 5` alphabetically.
        const timeline = buildKsHistory([schoolRow([2, 3, 12, 27, 21, 14])], 'Deutsch', 'le');
        expect(Object.keys(timeline[0].categories)).toEqual(LEVELS);
    });

    it('carries provenance from properties[simulated]', () => {
        const timeline = buildKsHistory(
            [
                schoolRow([1, 2, 3, 4, 5, 6], { year: '2025', simulated: true }),
                schoolRow([2, 3, 12, 27, 21, 14], { year: '2026' }),
            ],
            'Deutsch',
            'le',
        );

        expect(timeline.map((entry) => [entry.year, entry.measured])).toEqual([
            ['2025', false],
            ['2026', true],
        ]);
    });

    it('matches a Fach that has no Domäne split on a null domain', () => {
        // WHY: Mathematik ships `domain.id === null` in this payload. Matching it with a
        // truthy test drops the whole subject's timeline, and the card renders empty on a
        // dataset that has the data.
        const history = [
            {
                ...schoolRow([2, 3, 12, 27, 21, 14], { fach: 'Mathematik' }),
                domain: null,
            },
        ];

        expect(buildKsHistory(history, 'Mathematik', null)).toHaveLength(1);
        expect(buildKsHistory(history, 'Mathematik', 'le')).toEqual([]);
    });

    it('ignores anything that is not a school row', () => {
        // WHY: one document carries school rows and student rows. A student row has an
        // empty `competenceLevels`, so counting it as a year would emit a year with no
        // bands and break the connecting lines.
        const history = [schoolRow([2, 3, 12, 27, 21, 14]), studentRow('a')];
        expect(buildKsHistory(history, 'Deutsch', 'le')).toHaveLength(1);
    });

    it('drops a year nobody placed on the scale rather than dividing by its cohort', () => {
        // WHY: this is the failure the deleted generator produced — N empty bands floored
        // and renormalised into N identical lines at 100/N %, which looked exactly like a
        // finding. A year with a cohort but no placements has nothing to plot.
        const empty = schoolRow([0, 0, 0, 0, 0, 0]);
        empty.competenceLevels.forEach((level) => {
            level.descriptiveStatistics.total = 24;
        });

        expect(buildKsHistory([empty], 'Deutsch', 'le')).toEqual([]);
    });
});

describe('buildSurveyHistory', () => {
    it('averages a student across subjects before the cohort average', () => {
        // WHY: Selbstwirksamkeit is asked once per student but repeats on the row of every
        // Fach they sat. Pooling the rows would weight a student sitting four subjects
        // four times as heavily as one sitting one.
        const history = [
            studentRow('a', { fach: 'Deutsch', sp: '2.0' }),
            studentRow('a', { fach: 'Englisch', sp: '4.0' }),
            studentRow('b', { fach: 'Deutsch', sp: '5.0' }),
        ];

        const [slice] = buildSurveyHistory(history, 'sp_mean');
        expect([...slice.values].sort((a, b) => a - b)).toEqual([3, 5]);
    });

    it('restricts to one Fach and one student set when asked', () => {
        // WHY: "Unterrichtsqualität in Deutsch" must report the Deutsch cohort. Without
        // both filters the card shows the whole school under a subject-specific title.
        const history = [
            studentRow('a', { fach: 'Deutsch', tq: '2.0' }),
            studentRow('b', { fach: 'Deutsch', tq: '3.0' }),
            studentRow('a', { fach: 'Englisch', tq: '5.0' }),
        ];

        const [slice] = buildSurveyHistory(history, 'tq_mean', {
            subject: 'Deutsch',
            studentIds: new Set(['a']),
        });
        expect(slice.values).toEqual([2]);
    });

    it('separates the years and marks the generated ones', () => {
        const history = [
            studentRow('a', { year: '2025', simulated: true, tq: '2.0' }),
            studentRow('a', { year: '2026', tq: '4.0' }),
        ];

        expect(buildSurveyHistory(history, 'tq_mean')).toEqual([
            { year: '2025', measured: false, values: [2] },
            { year: '2026', measured: true, values: [4] },
        ]);
    });

    it('is empty when the scope carries no survey properties at all', () => {
        // WHY: a live scope without questionnaire data lands here, and both survey cards
        // must degrade to their empty state — not to a chart drawn from nothing.
        const history = [
            schoolRow([2, 3, 12, 27, 21, 14]),
            studentRow('a', { tq: null, sp: null }),
        ];

        expect(buildSurveyHistory(history, 'tq_mean')).toEqual([]);
        expect(buildSurveyHistory(history, 'sp_mean')).toEqual([]);
    });

    it('skips a row whose value is not a number instead of poisoning the average', () => {
        // WHY: one NaN turns the year's mean, SD and every quartile into NaN, and the box
        // plot draws with `NaN` coordinates — an invisible box on a chart that reports no
        // error.
        const history = [studentRow('a', { tq: 'k.A.' }), studentRow('b', { tq: '3.0' })];

        expect(buildSurveyHistory(history, 'tq_mean')[0].values).toEqual([3]);
    });
});

describe('detectHistorySurveyScales', () => {
    it('reports no survey timeline for a document with school rows only', () => {
        // WHY: the survey cards and the boxplot toggle gate on this. A dataset whose
        // student document ships `tq_mean` but whose history carries no student row
        // would otherwise build cards that can only ever draw their empty state.
        expect(detectHistorySurveyScales([schoolRow([2, 3, 12, 27, 21, 14])])).toEqual({
            hasTeachingQuality: false,
            hasSelfEfficacy: false,
        });
        expect(detectHistorySurveyScales(null)).toEqual({
            hasTeachingQuality: false,
            hasSelfEfficacy: false,
        });
    });

    it('reports each scale the student rows carry a value for', () => {
        const history = [
            schoolRow([2, 3, 12, 27, 21, 14]),
            studentRow('a', { tq: '3.1', sp: null }),
            studentRow('b', { year: '2025', simulated: true, tq: '2.9', sp: null }),
        ];

        expect(detectHistorySurveyScales(history)).toEqual({
            hasTeachingQuality: true,
            hasSelfEfficacy: false,
        });
    });
});
