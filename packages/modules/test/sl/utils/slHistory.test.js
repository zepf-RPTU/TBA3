import { beforeEach, describe, it, expect } from 'vitest';

import { createTestContext } from '../../support/glossaryFixture.js';
import {
    buildCompetenceLevelHistory,
    buildLongitudinalSubjectDomains,
    buildSurveyHistory,
    detectHistorySurveyScales,
    indexHistory,
} from '../../../src/sl/utils/slHistory.js';
import { buildLongitudinalTimelines } from '../../../src/sl/utils/slLongitudinalTimelines.js';
import { KS_LEVELS } from '../../support/competenceScaleFixture.js';

/**
 * A value group listing `names` as its levels, as `scaleIdOf` reads one.
 * @param {string[]} names
 * @returns {{competenceLevels: Array<{nameShort: string}>}}
 */
const levelRun = (names) => ({ competenceLevels: names.map((nameShort) => ({ nameShort })) });

/**
 * The SL Entwicklung view reads its earlier years out of the timeline value groups, which the
 * API answers `?comparison=year` with; it never invents them in the browser.
 *
 * Everything pinned here is a property of that read path that a chart cannot show is
 * broken: an earlier year misread as the current one, a timeline drawn in the wrong order or
 * a cohort silently mixed all render as clean, confident charts that say something
 * false. The demo fixture is regenerated by `tools/gen-sl-history-fixture.mjs`, so
 * these must hold for whatever it produces, not for one frozen file.
 */

/**
 * A school value group of one year on the `KS` ladder.
 * @param {number[]} counts - Headcount per level, lowest first; a missing one is 0.
 * @param {object} [options] - Where and when.
 * @param {string} [options.year] - The `testPeriod`.
 * @param {string} [options.subjectName]
 * @param {string|null} [options.domainId] - None when `null`.
 * @param {string} [options.domainName] - The Domäne's name; its id when absent.
 * @returns {import('../../../src/common/data/schemas/competenceLevels.js').CompetenceLevelsValueGroup}
 */
function schoolValueGroup(
    counts,
    { year = '2026', subjectName = 'Deutsch', domainId = 'le', domainName } = {},
) {
    const total = counts.reduce((sum, count) => sum + count, 0);
    return {
        id: 'school-1',
        type: 'school',
        name: 'Beispielschule',
        subject: { name: subjectName },
        domain: domainId === null ? undefined : { id: domainId, name: domainName ?? domainId },
        properties: [{ key: 'testPeriod', value: year }],
        competenceLevels: KS_LEVELS.map((nameShort, index) => ({
            nameShort,
            descriptiveStatistics: {
                total,
                frequency: counts[index] ?? 0,
                mean: total ? (counts[index] ?? 0) / total : 0,
            },
        })),
    };
}

/**
 * A student value group of one year with its survey means.
 * @param {string} id - The student id, also its name.
 * @param {object} [options] - Where, when and what.
 * @param {string} [options.year] - The `testPeriod`.
 * @param {string} [options.subjectName]
 * @param {string} [options.domainId] - None when absent.
 * @param {string|null} [options.tq] - The `tq_mean`; none when `null`.
 * @param {string|null} [options.sp] - The `sp_mean`; none when `null`.
 * @returns {import('../../../src/common/data/schemas/competenceLevels.js').CompetenceLevelsValueGroup}
 */
function surveyStudentValueGroup(
    id,
    { year = '2026', subjectName = 'Deutsch', domainId = undefined, tq = '3.0', sp = '4.0' } = {},
) {
    return {
        id,
        type: 'student',
        name: id,
        subject: { name: subjectName },
        ...(domainId === undefined ? {} : { domain: { id: domainId, name: domainId } }),
        properties: [
            ...(tq === null ? [] : [{ key: 'tq_mean', value: tq }]),
            ...(sp === null ? [] : [{ key: 'sp_mean', value: sp }]),
            { key: 'testPeriod', value: year },
        ],
        competenceLevels: [],
    };
}

/** @type {import('../../../src/common/services/competenceLevelPalette.js').CompetenceLevelPalette} */
let palette;

beforeEach(() => {
    palette = createTestContext('sl').palette;
});

describe('indexHistory years', () => {
    it('sorts numerically and de-duplicates, whatever order the payload used', () => {
        // The box plot feeds this straight into `d3.scalePoint().domain()`, which
        // preserves array order. The server emits the current year before the earlier
        // ones, so payload order puts the newest year first — drawn as-is that reads as a
        // four-year decline. Every year also appears on many value groups (one per Fach/Domäne
        // plus every student), so a duplicate would collapse the axis onto itself.
        const current = [
            schoolValueGroup([1, 1, 1, 1, 1, 1], { year: '2026' }),
            surveyStudentValueGroup('a', { year: '2026' }),
        ];
        const earlier = [
            schoolValueGroup([1, 1, 1, 1, 1, 1], { year: '2024' }),
            schoolValueGroup([1, 1, 1, 1, 1, 1], { year: '2025' }),
            schoolValueGroup([1, 1, 1, 1, 1, 1], { year: '2024', subjectName: 'Englisch' }),
        ];

        expect(indexHistory(palette, current, earlier).years).toEqual(['2024', '2025', '2026']);
    });

    it("names the current year after the current value groups' stamp", () => {
        // The Material page's year badge reads it. The store has already taken the
        // current year from the answer's first block, so a later stamp among the earlier
        // years does not make that one current.
        const index = indexHistory(
            palette,
            [schoolValueGroup([1, 1, 1, 1, 1, 1], { year: '2025' })],
            [schoolValueGroup([1, 1, 1, 1, 1, 1], { year: '2026' })],
        );

        expect(index.currentYear).toBe('2025');
    });

    it('is empty for an empty document rather than throwing', () => {
        // A dataset whose timeline is empty must still render the host's empty
        // state instead of taking the view down.
        expect(indexHistory(palette, [], []).years).toEqual([]);
    });
});

describe('buildCompetenceLevelHistory', () => {
    it('reports shares from frequency and total, not from the payload mean', () => {
        // `mean` is rounded to 4 dp at the source (0.0253 for 2/79). The chart stacks
        // these shares to 100 %, and rounded ones do not add up — the top band would be
        // visibly short of the axis.
        const timeline = buildCompetenceLevelHistory(
            indexHistory(palette, [schoolValueGroup([2, 3, 12, 27, 21, 14])], []),
            'Deutsch',
            'le',
        );

        expect(timeline).toHaveLength(1);
        const shares = Object.values(timeline[0].categories);
        expect(shares.reduce((sum, share) => sum + share, 0)).toBeCloseTo(100, 10);
        expect(timeline[0].categories['KS 3']).toBeCloseTo((27 / 79) * 100, 10);
    });

    it('keeps the payload band order, which Object.keys would re-sort', () => {
        // The legend and the stacking order follow these keys. `k.h.N.` is the lowest
        // rung and sorts after `KS 5` alphabetically.
        const timeline = buildCompetenceLevelHistory(
            indexHistory(palette, [schoolValueGroup([2, 3, 12, 27, 21, 14])], []),
            'Deutsch',
            'le',
        );
        expect(Object.keys(timeline[0].categories)).toEqual(KS_LEVELS);
    });

    it('orders the timeline oldest-first however the payload arrived', () => {
        // The x-scale takes the years in array order, and the server emits the
        // earlier years after the current one: unsorted, 2026 draws before 2025.
        const timeline = buildCompetenceLevelHistory(
            indexHistory(
                palette,
                [schoolValueGroup([2, 4, 6, 8, 3, 1], { year: '2026' })],
                [
                    schoolValueGroup([1, 3, 7, 9, 3, 1], { year: '2024' }),
                    schoolValueGroup([3, 3, 6, 8, 3, 1], { year: '2025' }),
                ],
            ),
            'Deutsch',
            'le',
        );

        expect(timeline.map((entry) => entry.year)).toEqual(['2024', '2025', '2026']);
    });

    it('ignores value groups for another Fach or Domäne', () => {
        // One history document carries every (Fach, Domäne) the school sat. Matching
        // loosely would stack Englisch's bands onto Deutsch's chart: the shares would
        // exceed 100 % and the legend would name levels twice.
        const timeline = buildCompetenceLevelHistory(
            indexHistory(
                palette,
                [
                    schoolValueGroup([2, 4, 6, 8, 3, 1]),
                    schoolValueGroup([9, 9, 9, 9, 9, 9], { subjectName: 'Englisch' }),
                    schoolValueGroup([9, 9, 9, 9, 9, 9], { domainId: 'rs' }),
                ],
                [],
            ),
            'Deutsch',
            'le',
        );

        expect(timeline).toHaveLength(1);
        expect(timeline[0].categories['KS 3']).toBeCloseTo((8 / 24) * 100, 10);
    });

    it('returns nothing for an empty history document', () => {
        // A dataset whose acquisition delivered no timeline must render the
        // host's empty state rather than take the view down.
        expect(buildCompetenceLevelHistory(indexHistory(palette, [], []), 'Deutsch', 'le')).toEqual(
            [],
        );
    });

    it('matches a Fach that has no Domäne split on a missing domain', () => {
        // Mathematik ships no `domain` in this payload. Matching it with a
        // truthy test drops the whole subject's timeline, and the card renders empty on a
        // dataset that has the data.
        const history = [
            schoolValueGroup([2, 3, 12, 27, 21, 14], { subjectName: 'Mathematik', domainId: null }),
        ];

        expect(
            buildCompetenceLevelHistory(indexHistory(palette, history, []), 'Mathematik', null),
        ).toHaveLength(1);
        expect(
            buildCompetenceLevelHistory(indexHistory(palette, history, []), 'Mathematik', 'le'),
        ).toEqual([]);
    });

    it('ignores anything that is not a school value group', () => {
        // One document carries school value groups and student value groups. A student value group has an
        // empty `competenceLevels`, so counting it as a year would emit a year with no
        // bands and break the connecting lines.
        const history = [schoolValueGroup([2, 3, 12, 27, 21, 14]), surveyStudentValueGroup('a')];
        expect(
            buildCompetenceLevelHistory(indexHistory(palette, history, []), 'Deutsch', 'le'),
        ).toHaveLength(1);
    });

    it('drops a year nobody placed on the scale rather than dividing by its cohort', () => {
        // N empty bands floored and renormalised come out as N identical lines at
        // 100/N %, which looks exactly like a finding. A year with a cohort but no
        // placements has nothing to plot.
        const empty = schoolValueGroup([0, 0, 0, 0, 0, 0]);
        empty.competenceLevels.forEach((level) => {
            level.descriptiveStatistics.total = 24;
        });

        expect(
            buildCompetenceLevelHistory(indexHistory(palette, [empty], []), 'Deutsch', 'le'),
        ).toEqual([]);
    });
});

describe('buildSurveyHistory', () => {
    it('averages a student across subjects before the cohort average', () => {
        // Selbstwirksamkeit is asked once per student but repeats on the value group of every
        // Fach they sat. Pooling the value groups would weight a student sitting four subjects
        // four times as heavily as one sitting one.
        const history = [
            surveyStudentValueGroup('a', { subjectName: 'Deutsch', sp: '2.0' }),
            surveyStudentValueGroup('a', { subjectName: 'Englisch', sp: '4.0' }),
            surveyStudentValueGroup('b', { subjectName: 'Deutsch', sp: '5.0' }),
        ];

        const [slice] = buildSurveyHistory(indexHistory(palette, history, []), 'selfEfficacyMean');
        expect([...slice.values].sort((a, b) => a - b)).toEqual([3, 5]);
    });

    it('restricts to one Fach and one Domäne when asked', () => {
        // "Unterrichtsqualität in Deutsch: Lesen" must report the Lesen students. Without
        // both filters the card shows the whole school under a subject-specific title.
        const history = [
            surveyStudentValueGroup('a', { domainId: 'le', tq: '2.0' }),
            surveyStudentValueGroup('b', { domainId: 'rs', tq: '3.0' }),
            surveyStudentValueGroup('a', { subjectName: 'Englisch', domainId: 'le', tq: '5.0' }),
        ];

        const [slice] = buildSurveyHistory(
            indexHistory(palette, history, []),
            'teachingQualityMean',
            { subject: 'Deutsch', domainId: 'le' },
        );
        expect(slice.values).toEqual([2]);
    });

    it('separates the years', () => {
        const index = indexHistory(
            palette,
            [surveyStudentValueGroup('a', { year: '2026', tq: '4.0' })],
            [surveyStudentValueGroup('a', { year: '2025', tq: '2.0' })],
        );

        expect(buildSurveyHistory(index, 'teachingQualityMean')).toEqual([
            { year: '2025', values: [2] },
            { year: '2026', values: [4] },
        ]);
    });

    it('is empty when the scope carries no survey properties at all', () => {
        // A live scope without questionnaire data lands here, and both survey cards
        // must degrade to their empty state — not to a chart drawn from nothing.
        const history = [
            schoolValueGroup([2, 3, 12, 27, 21, 14]),
            surveyStudentValueGroup('a', { tq: null, sp: null }),
        ];

        expect(
            buildSurveyHistory(indexHistory(palette, history, []), 'teachingQualityMean'),
        ).toEqual([]);
        expect(buildSurveyHistory(indexHistory(palette, history, []), 'selfEfficacyMean')).toEqual(
            [],
        );
    });

    it('skips a value group whose value is not a number instead of poisoning the average', () => {
        // One NaN turns the year's mean, SD and every quartile into NaN, and the box
        // plot draws with `NaN` coordinates — an invisible box on a chart that reports no
        // error.
        const history = [
            surveyStudentValueGroup('a', { tq: 'k.A.' }),
            surveyStudentValueGroup('b', { tq: '3.0' }),
        ];

        expect(
            buildSurveyHistory(indexHistory(palette, history, []), 'teachingQualityMean')[0].values,
        ).toEqual([3]);
    });
});

describe('detectHistorySurveyScales', () => {
    it('reports no survey timeline for a document with school value groups only', () => {
        // The survey cards and the boxplot toggle gate on this. A dataset whose
        // student document ships `tq_mean` but whose history carries no student value group
        // would otherwise build cards that can only ever draw their empty state.
        expect(
            detectHistorySurveyScales(
                indexHistory(palette, [schoolValueGroup([2, 3, 12, 27, 21, 14])], []),
            ),
        ).toEqual({
            hasTeachingQuality: false,
            hasSelfEfficacy: false,
            offersBoxPlot: false,
        });
    });

    it('reports each scale the student value groups carry a value for', () => {
        const index = indexHistory(
            palette,
            [
                schoolValueGroup([2, 3, 12, 27, 21, 14]),
                surveyStudentValueGroup('a', { tq: '3.1', sp: null }),
            ],
            [surveyStudentValueGroup('b', { year: '2025', tq: '2.9', sp: null })],
        );

        expect(detectHistorySurveyScales(index)).toEqual({
            hasTeachingQuality: true,
            hasSelfEfficacy: false,
            // The box plot replaces both survey cards, so it needs both.
            offersBoxPlot: false,
        });
    });
});

describe('buildLongitudinalSubjectDomains', () => {
    /**
     * A current-year school value group that lists only some of the ladder's levels.
     * @param {string[]} levels - The levels it lists.
     * @param {object} [options] - Where.
     * @param {string} [options.subjectName]
     * @param {string|null} [options.domainId] - None when `null`.
     * @param {string} [options.name] - The Domäne's name.
     * @returns {import('../../../src/common/data/schemas/competenceLevels.js').CompetenceLevelsValueGroup}
     */
    function truncatedValueGroup(levels, { subjectName = 'Deutsch', domainId = 'le', name } = {}) {
        return {
            ...schoolValueGroup([], { subjectName, domainId, domainName: name }),
            competenceLevels: levels.map((nameShort) => ({
                nameShort,
                descriptiveStatistics: { total: 10, frequency: 1, mean: 0.1 },
            })),
        };
    }

    it("lists every current year's (Fach, Domäne) Fach by Fach, labelled for the selector", () => {
        // The selector's index is what the header writes back, and every card reads
        // `subjectDomains[index]`. The Fächer come in payload order with their Domänen kept
        // together, and a Fach with a single Bereich is named by the Fach alone.
        const subjectDomains = buildLongitudinalSubjectDomains(
            indexHistory(
                palette,
                [
                    truncatedValueGroup(KS_LEVELS, { domainId: 'le', name: 'Lesen' }),
                    truncatedValueGroup(KS_LEVELS, { subjectName: 'Mathematik', domainId: null }),
                    truncatedValueGroup(KS_LEVELS, { domainId: 'rs', name: 'Rechtschreibung' }),
                ],
                [],
            ),
        );

        expect(
            subjectDomains.map(({ subjectName, domainId, label }) => [
                subjectName,
                domainId,
                label,
            ]),
        ).toEqual([
            ['Deutsch', 'le', 'Deutsch: Lesen'],
            ['Deutsch', 'rs', 'Deutsch: Rechtschreibung'],
            ['Mathematik', null, 'Mathematik'],
        ]);
    });

    it('leaves a Bereich only an earlier year covers out of the selector', () => {
        // The cards show the Bereiche the school sat this year; one only an
        // earlier year carries has no current result to anchor it and gets no card.
        const subjectDomains = buildLongitudinalSubjectDomains(
            indexHistory(
                palette,
                [schoolValueGroup([1, 1, 1, 1, 1, 1])],
                [schoolValueGroup([1, 1, 1, 1, 1, 1], { year: '2025', domainId: 'rs' })],
            ),
        );

        expect(subjectDomains.map((subjectDomain) => subjectDomain.domainId)).toEqual(['le']);
    });

    it("reads the ladder off the scale the current year's value group resolves to, in payload order", () => {
        // A value group lists only the levels its population reached, so the current value group
        // alone can miss a band: the registered scale has them all. Integer-like names
        // ('1a', '2') are the reason the order is kept as an array: object keys would come
        // back re-sorted. An earlier year on another registered scale does not count.
        const ladder = ['1a', '1b', '2', '3'];
        const earlier = ['A', 'B', 'C'];
        palette.registerCompetenceLevelScales([
            truncatedValueGroup(ladder),
            truncatedValueGroup(earlier, { subjectName: 'Mathematik' }),
        ]);

        const [subjectDomain] = buildLongitudinalSubjectDomains(
            indexHistory(
                palette,
                [truncatedValueGroup(['1b', '2'])],
                [
                    {
                        ...truncatedValueGroup(earlier),
                        properties: schoolValueGroup([], { year: '2025' }).properties,
                    },
                ],
            ),
        );

        expect(subjectDomain.competenceLevelNames).toEqual(ladder);
        expect(subjectDomain.scaleId).toBe(palette.scaleIdOf(levelRun(ladder)));
        expect(subjectDomain.scaleId).toBeDefined();
    });

    it("reads each year's Unterrichtsqualität off that year's students of the Bereich", () => {
        // VERA tests a Jahrgang each year, so an earlier year's students are other
        // students: the current year's ids select nothing there. Each year counts the
        // value groups of the Bereich's Fach and Domäne — another Domäne's stays out, and
        // one without a Domäne stands for the whole Fach.
        const index = indexHistory(
            palette,
            [
                schoolValueGroup([1, 1, 1, 1, 1, 1]),
                schoolValueGroup([1, 1, 1, 1, 1, 1], { domainId: 'rs' }),
                surveyStudentValueGroup('a', { domainId: 'le', tq: '4.5' }),
                surveyStudentValueGroup('b', { domainId: 'rs', tq: '1.5' }),
            ],
            [
                surveyStudentValueGroup('c', { year: '2025', tq: '2.5' }),
                surveyStudentValueGroup('d', { year: '2024', domainId: 'le', tq: '3.5' }),
                surveyStudentValueGroup('e', { year: '2024', domainId: 'rs', tq: '1.5' }),
            ],
        );
        const subjectDomains = buildLongitudinalSubjectDomains(index);

        const [lesen] = buildLongitudinalTimelines(index, subjectDomains).bySubjectDomain;
        expect(lesen.teachingQuality).toEqual([
            { year: '2024', categories: { low: 0, medium: 0, good: 100, excellent: 0 } },
            { year: '2025', categories: { low: 0, medium: 100, good: 0, excellent: 0 } },
            { year: '2026', categories: { low: 0, medium: 0, good: 0, excellent: 100 } },
        ]);
    });

    it('returns no subject domains for an empty document', () => {
        expect(buildLongitudinalSubjectDomains(indexHistory(palette, [], []))).toEqual([]);
    });
});
